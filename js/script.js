function applyLanguage(lang) {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.pt;

  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  const langMap = { pt: 'pt-BR', en: 'en', ja: 'ja' };
  document.documentElement.lang = langMap[lang] || 'pt-BR';

  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });

  try {
    localStorage.setItem('gm_site_lang', lang);
  } catch (e) {
    /* localStorage unavailable, ignore */
  }
}

document.addEventListener('DOMContentLoaded', function () {
  document.querySelectorAll('.lang-btn').forEach(function (btn) {
    btn.addEventListener('click', function () {
      applyLanguage(btn.getAttribute('data-lang'));
    });
  });

  let startLang = 'pt';
  try {
    const saved = localStorage.getItem('gm_site_lang');
    if (saved && TRANSLATIONS[saved]) startLang = saved;
  } catch (e) {
    /* localStorage unavailable, ignore */
  }

  applyLanguage(startLang);
});
